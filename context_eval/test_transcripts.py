"""Long-context test transcripts for the context-management strategy eval.

Models Swiftrail's real failure mode: a long triage/dispute call where a
customer or ops detail mentioned early (a credit dispute, a damaged-goods
claim, a standing discount agreement) has to survive dozens of turns of
tool-call noise (shipment lookups, invoice pulls, rate lookups) until it's
needed again near the end of the call.

Each transcript is a list of message dicts (role/content), matching the
``ContextStrategy.apply`` interface in strategies/base.py. The critical
fact is planted at a fixed early turn and re-asked for at the final turn;
``evaluate_strategies.py`` checks whether it's still recoverable after
each strategy prunes the transcript.

10 variations are generated by rotating the customer, the critical fact,
and the amount of tool noise, so the eval isn't scored against a single
lucky (or unlucky) transcript shape.
"""

from __future__ import annotations

import random
from dataclasses import dataclass

TOOL_EVENTS = [
    ("get_shipment_status", '{{"shipment_id": {sid}, "status": "in_transit", "eta": "2026-08-{day:02d}"}}'),
    ("list_customer_invoices", '{{"customer_id": {cid}, "invoice_count": {n}, "total_due": "{amt}.00"}}'),
    ("run_portfolio_risk_sweep", '{{"customer_id": {cid}, "risk_score": {score}, "flags": []}}'),
    ("search_customer", '{{"id": {cid}, "name": "Customer {cid} Ltd", "credit_status": "active"}}'),
    ("get_shipment_status", '{{"shipment_id": {sid}, "status": "delivered", "pod_signed": true}}'),
    ("list_customer_invoices", '{{"customer_id": {cid}, "invoice_count": {n}, "overdue_count": 0}}'),
]

CRITICAL_FACTS = [
    "customer disputed invoice {iid} citing a billing error on the fuel surcharge line",
    "customer has a standing 12% loyalty discount approved by the regional manager",
    "shipment {sid} was damaged in transit and a claim was opened with the carrier",
    "customer's primary contact changed and the old contact should no longer get invoices",
    "customer requested all future rate exceptions be routed to finance, not sales",
]

FINAL_QUESTIONS = [
    "before we send the new invoice, any billing disputes I should know about?",
    "are there any special discount terms on this account before I quote the customer?",
    "any open claims on this customer's shipments before I confirm the delivery note?",
    "who should invoices go to on this account?",
    "any routing exceptions I should follow before approving this discount?",
]


@dataclass
class EvaluationTranscript:
    name: str
    messages: list[dict]
    critical_fact: str
    final_question: str


def _tool_noise_turn(rng: random.Random, cid: int, sid: int) -> dict:
    name, template = rng.choice(TOOL_EVENTS)
    content = template.format(
        sid=sid, cid=cid, n=rng.randint(1, 9),
        amt=rng.randint(500, 90000), day=rng.randint(1, 28),
        score=rng.randint(1, 99),
    )
    return {"role": "tool", "name": name, "content": content}


def make_transcript(index: int, noise_turns: int, seed: int) -> EvaluationTranscript:
    """Build one long transcript with a critical fact buried under noise."""
    rng = random.Random(seed)
    cid = 100 + index
    sid = 500 + index
    iid = 900 + index

    fact = CRITICAL_FACTS[index % len(CRITICAL_FACTS)].format(iid=iid, sid=sid)
    question = FINAL_QUESTIONS[index % len(FINAL_QUESTIONS)]

    messages: list[dict] = [
        {"role": "system", "content": "You are the Swiftrail logistics assistant. Ground every answer in tool results and prior turns."},
        {"role": "employee", "content": f"hi, pulling up customer {cid} for shipment {sid}"},
        {"role": "tool", "name": "search_customer", "content": f'{{"id": {cid}, "name": "Customer {cid} Ltd"}}'},
        # critical fact planted early, at a fixed low turn index
        {"role": "employee", "content": f"quick note before we go further -- {fact}"},
        {"role": "agent", "content": "Got it, noting that for this account."},
    ]

    for i in range(noise_turns):
        messages.append(_tool_noise_turn(rng, cid, sid + i))
        if i % 4 == 0:
            messages.append({"role": "employee", "content": f"ok what's next on shipment {sid + i}"})
            messages.append({"role": "agent", "content": "Checking that now."})

    messages.append({"role": "employee", "content": question})

    return EvaluationTranscript(
        name=f"transcript_{index:02d}_noise{noise_turns}",
        messages=messages,
        critical_fact=fact,
        final_question=question,
    )


def build_test_suite() -> list[EvaluationTranscript]:
    """10 fixed transcript variations. Do not change once evaluation starts."""
    noise_levels = [30, 35, 32, 40, 28, 36, 33, 45, 30, 38]
    return [
        make_transcript(i, noise_turns=noise_levels[i], seed=1000 + i)
        for i in range(10)
    ]
